from pydantic import BaseModel, Field
from typing import Literal


class TutorAgentState(BaseModel):
    StudentQuery: str = Field(default="", description="The query from the student.")
    AgentAction: str = Field(default="", description="The action taken by the agent.")
    RetrievedInfo: str = Field(default="", description="The information retrieved from the retriever node.")
    WebInfo: str = Field(default="", description="The information retrieved from the web node.")
    planInfo: str = Field(default="", description="The plan generated by the planner node.")
    Escalate: bool = Field(default=False, description="Whether to escalate to a human tutor.")
    

class TutorInputState(BaseModel):
    StudentQuery: str = Field(default="", description="The query from the student.")

class OrchestratorConfig(BaseModel):
    route: Literal["web", "answer"] = Field(description="If retrieved info is sufficient to answer the student query, choose 'answer'.  If the student query requires fresh/current/external information or retrieved info is unrelated or need more information on the user query, choose 'web'.")
    reason: str

class PlannerConfig(BaseModel):
    plan: str = Field(description="The plan to answer the student query based on the retrieved info. If the student query is straightforward and can be directly answered by retrieved info, return a plan to answer the student query. If the student query is complex and requires multiple steps of reasoning, return a plan with multiple steps to answer the student query.")

class TutorConfig(BaseModel):
    answer: str = Field(description="The answer to the student query based on the plan. Follow the plan step by step to answer the student query. If the plan is straightforward and can be directly answered, answer the student query directly. If the plan is complex and requires multiple steps of reasoning, follow the plan step by step to answer the student query. If the plan is not helpful to answer the student query, DO NOT answer reply mention that you don't have the necessary information.")