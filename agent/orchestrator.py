import os
from langchain_core.messages import SystemMessage, HumanMessage


from .models import OrchestratorConfig,TutorAgentState
from .llm import LLMClient



_system_message = """
You are the Orchestrator Agent, the central decision-maker in an AI system. Your primary objective is to evaluate whether the currently available information is sufficient to comprehensively and accurately answer the user's query.

You will be provided with three inputs:
1. **User Query:** The original question or task requested by the user.
2. **Planner Strategy:** A step-by-step plan or context generated by the Planner Agent on how to tackle the user's query.
3. **Retrieved Information:** The data currently available from internal databases or previous steps.

**Your Task:**
Analyze the `Retrieved Information` against the `User Query` and the `Planner Strategy`. 
- If the retrieved information is complete, accurate, and sufficient to fully satisfy the user's query without hallucinating, you must proceed to answer.
- If the retrieved information is missing key details, outdated, or insufficient to fulfill the planner's strategy, you must invoke a web search to gather the missing data.
"""


def _build_context(state:TutorAgentState)->str:
    """
        Build the context for the orchestrator node based on the current state of the tutor agent.
    """
    user_query = state.query 
    retrieved_info = None

    if state.Retriver_info:
        retrieved_info = state.Retriver_info

    orchestrator_context = f"""Please evaluate the following context and decide on the next action.

    **User Query:** {user_query}

    **Retrieved Information:** {retrieved_info}

    Based on the instructions in your system prompt, output your JSON response now.
    """
    return  orchestrator_context

def orchestrator_node(state: TutorAgentState) -> dict:
    api_key = os.getenv("OPENAI_API_KEY")

    client = LLMClient(api_key=api_key)

    response: OrchestratorConfig = client.generate_response(
        model="gpt-5-mini",
        input=[
            {"role": "system", "content": _system_message},
            {"role": "user", "content": _build_context(state)},
        ],
        text_format=OrchestratorConfig,
    )

    print(f"Orchestrator decision: {response}")

    if response.action not in ["SEARCH", "ANSWER","TUTOR"]:
        raise ValueError(
            f"Invalid response from orchestrator node. Expected SEARCH or ANSWER, got {response.action}"
        )


    # orchestrator.py
    return {
        "Orchestartor_info": response.reasoning,
        "orchestrator_action": response.action,
        "search_queries": response.search_queries or [],
        "voice_status": (
            "The internal information is enough. I will explain it now."
            if response.action == "ANSWER"
            else "The internal information is not enough, so I am checking the web."
        ),
    }
    